  function roadFrames() {
    var width = 30, x = 0, speed = 1, frames = [];
    for (var frame = 0; frame < 90; frame++) {
      var road = new Array(width).fill('.');
      road[x] = 'O';
      frames.push('|' + road.join('') + '|');
      x = x + speed;
      if (x === width - 1 || x === 0) speed = -speed;
    }
    return frames;
  }

