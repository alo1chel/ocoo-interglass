  function ballFrames() {
    var W = 20, H = 8, b = { x: 1, y: 1, dx: 1, dy: 1 }, frames = [];
    for (var frame = 0; frame < 60; frame++) {
      var rows = [];
      for (var row = 0; row < H; row++) {
        var s = '';
        for (var col = 0; col < W; col++) s += (row === b.y && col === b.x) ? 'O' : '.';
        rows.push(s);
      }
      frames.push(rows.join('\n'));
      b.x += b.dx; b.y += b.dy;
      if (b.x === 0 || b.x === W - 1) b.dx = -b.dx;
      if (b.y === 0 || b.y === H - 1) b.dy = -b.dy;
    }
    return frames;
  }

